import { mkdir, readFile, writeFile } from "node:fs/promises"
import { dirname, resolve } from "node:path"
import { pbkdf2Sync, randomBytes } from "node:crypto"

const localConfigPath = resolve(".protect.local.json")
const outputPath = resolve("quartz/protect.generated.ts")
const passwordContext = "quartz-protect-v1"
const kdfIterations = 150000
const keyLengthBytes = 32
const digest = "sha256"

function normalizePassword(value) {
  if (typeof value !== "string" || value.length === 0) {
    throw new Error('.protect.local.json must contain a non-empty string field named "password"')
  }
  return value
}

const rawConfig = await readFile(localConfigPath, "utf8").catch((error) => {
  if (error.code === "ENOENT") {
    throw new Error(
      'Missing .protect.local.json. Create it with: { "password": "your-password" }',
    )
  }
  throw error
})

const config = JSON.parse(rawConfig)
const password = normalizePassword(config.password)
const salt = typeof config.salt === "string" && config.salt.length > 0
  ? Buffer.from(config.salt, "hex")
  : randomBytes(16)

const passwordBytes = Buffer.from(`${passwordContext}:${password}`, "utf8")
const hash = pbkdf2Sync(passwordBytes, salt, kdfIterations, keyLengthBytes, digest).toString("hex")

const generated = `// Generated by scripts/generate-protect-config.mjs.\n// Commit this file, but do not commit .protect.local.json.\nexport const protectPasswordHash = ${JSON.stringify(hash)}\nexport const protectPasswordSalt = ${JSON.stringify(salt.toString("hex"))}\nexport const protectPasswordLength = ${password.length}\nexport const protectKdfIterations = ${kdfIterations}\n`

await mkdir(dirname(outputPath), { recursive: true })
await writeFile(outputPath, generated, "utf8")
console.log(`Wrote ${outputPath}`)
